    private function generateUniqueSlug($name, $provinceId)
    {
        $slug = Str::slug($name);
        $originalSlug = $slug;
        $counter = 1;
        while (DB::table('cities')
            ->where('slug', $slug)
            ->where('province_id', $provinceId)
            ->exists()
        ) {
            $slug = $originalSlug . '-' . $counter;
            $counter++;
        }

        return $slug;
    }

